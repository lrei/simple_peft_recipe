def _build_config(args: argparse.Namespace) -> PESFTConfig:
    """Map the CLI options onto a ``PESFTConfig`` for chat SFT.

    Fields not set here keep the ``PESFTConfig`` defaults (LoRA on all
    attention and MLP projections, per-epoch eval and save, best
    checkpoint by ``eval_loss`` reloaded at the end).

    Args:
        args: Options from ``parse_args``.

    Returns:
        The training configuration.
    """
    config = PESFTConfig()

    config.model_name_or_path = args.model_name_or_path
    config.max_seq_length = args.max_seq_length
    config.load_in_4bit = args.load_in_4bit

    # Loss only on assistant turns: tokens after response_part up to the
    # next instruction_part are trained. The markers are ChatML's, so they
    # match --chat_template chatml (and Qwen's own templates); another
    # template needs its own markers here.
    config.chat_template = args.chat_template
    config.train_on_responses = True
    config.instruction_part = "<|im_start|>user\n"
    config.response_part = "<|im_start|>assistant\n"

    config.lora_r = args.lora_r
    config.lora_alpha = args.lora_alpha

    config.learning_rate = args.learning_rate
    config.weight_decay = args.weight_decay
    config.scheduler = args.scheduler
    config.warmup_ratio = args.warmup_ratio
    config.per_device_train_batch_size = args.per_device_batch_size
    config.per_device_eval_batch_size = args.per_device_eval_batch_size
    config.gradient_accumulation_steps = args.gradient_accumulation_steps
    config.max_grad_norm = args.max_grad_norm
    config.num_train_epochs = args.num_epochs

    config.output_dir = args.output_dir
    config.save_method = args.save_method
    config.packing = args.packing
    config.random_state = args.random_state
    config.report_to = "none"

    return config


def _load_datasets(eval_ratio: float, seed: int) -> tuple[Dataset, Dataset]:
    """Load the Dolly pirate dataset and split off an evaluation set.

    Args:
        eval_ratio: Fraction of rows held out for evaluation, in (0, 1).
        seed: Seed for the random split.

    Returns:
        ``(train_dataset, eval_dataset)`` with the columns ``instruction``,
        ``context`` (often empty), ``response`` and ``category``.

    Raises:
        ValueError: If ``eval_ratio`` is not strictly between 0 and 1.
    """
    if not 0 < eval_ratio < 1:
        msg = "eval_ratio must be between 0 and 1 (exclusive)."
        raise ValueError(msg)

    dataset = cast("Dataset", load_dataset(DATASET_NAME, split="train"))
    split = dataset.train_test_split(test_size=eval_ratio, seed=seed)
    return split["train"], split["test"]


def main() -> None:
    """Instruction-tune the model and save it.

    Runs ``PESFT(config)`` then ``load_model()``, ``train()`` and
    ``save_model()``, printing one formatted training row first.

    Returns:
        None. The adapters (or merged model, per ``--save_method``),
        tokenizer, ``speftr.json``, ``training_args.json`` and per-epoch
        checkpoints are written to ``--output_dir``.
    """
    args = parse_args()
    print(unsloth.__version__)

    config = _build_config(args)
    trainer = PESFT(config)
    # The returned tokenizer already has the configured chat template.
    model, tokenizer = trainer.load_model()

    _disable_thinking_mode(model)
    system_prompt = _normalize_system_prompt(args.system_prompt)
    _set_default_system_prompt(tokenizer, system_prompt)

    format_batch = _build_format_batch(tokenizer, system_prompt)
    train_dataset, eval_dataset = _load_datasets(
        eval_ratio=args.eval_ratio,
        seed=config.random_state,
    )

    # Printing one rendered row is the quickest check that the template
    # and the instruction_part/response_part markers line up.
    preview_data = train_dataset[:1]
    preview_texts = format_batch(preview_data)
    if preview_texts:
        preview_header = "Preview: formatted conversation sent to the model"
        print(preview_header)
        print("-" * len(preview_header))
        print(preview_texts[0])
        print("-" * len(preview_header))

    trainer.train(train_dataset, eval_dataset, format_batch)
    trainer.save_model()


if __name__ == "__main__":
    main()
